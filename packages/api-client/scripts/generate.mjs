#!/usr/bin/env node
// Generates src/generated from the gateway's committed OpenAPI contract (apps/api-gateway/openapi.json):
//   node scripts/generate.mjs           writes src/generated
//   node scripts/generate.mjs --check   regenerates into a temp dir and fails if src/generated differs (part of `npm test`)
//
// Steps: (1) the X-School-Id header is removed from the operations before generation: the client injects it from the
// active school, so callers never pass it by hand; (2) @hey-api/openapi-ts writes types + SDK + fetch client;
// (3) routes.gen.ts records each route's access class so the transport knows which routes need a token or a school;
// (4) api.gen.ts is a thin facade whose every method throws on failure and returns the typed payload.
import { createClient } from '@hey-api/openapi-ts';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = resolve(ROOT, '../../apps/api-gateway/openapi.json');
const TARGET = resolve(ROOT, 'src/generated');
const check = process.argv.includes('--check');

const spec = JSON.parse(readFileSync(SPEC, 'utf8'));
const clientSpec = structuredClone(spec);
const HEADER_REFS = new Set(['#/components/parameters/SchoolId', '#/components/parameters/ActiveSchoolId']);
const routes = [];
for (const [path, item] of Object.entries(clientSpec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    routes.push({ method: method.toUpperCase(), path, access: op['x-access'], operationId: op.operationId });
    op.parameters = (op.parameters ?? []).filter((p) => !HEADER_REFS.has(p.$ref));
    if (op.parameters.length === 0) delete op.parameters;
  }
}
delete clientSpec.components.parameters?.SchoolId;
delete clientSpec.components.parameters?.ActiveSchoolId;
if (clientSpec.components.parameters && Object.keys(clientSpec.components.parameters).length === 0) delete clientSpec.components.parameters;
routes.sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
for (const r of routes) if (!['public', 'user', 'platform', 'tenant'].includes(r.access)) throw new Error(`${r.method} ${r.path}: missing x-access in the OpenAPI contract`);

const work = mkdtempSync(join(tmpdir(), 'oru-api-client-'));
const out = join(work, 'generated');
const specFile = join(work, 'openapi.client.json');
writeFileSync(specFile, JSON.stringify(clientSpec));
await createClient({ input: specFile, output: { path: out }, plugins: ['@hey-api/typescript', '@hey-api/sdk', '@hey-api/client-fetch'] });

// (3) the access table
writeFileSync(
  join(out, 'routes.gen.ts'),
  `// GENERATED by scripts/generate.mjs from apps/api-gateway/openapi.json. Do not edit.\n` +
    `export type Access = 'public' | 'user' | 'platform' | 'tenant';\n` +
    `export interface RouteInfo { method: string; path: string; access: Access; operationId: string }\n` +
    `export const ROUTES: readonly RouteInfo[] = ${JSON.stringify(routes, null, 2)};\n`,
);

// (4) the facade: one method per SDK function
const sdkText = readFileSync(join(out, 'sdk.gen.ts'), 'utf8');
const names = [...sdkText.matchAll(/^export const (\w+) = </gm)].map((m) => m[1]).sort();
if (names.length !== routes.length) throw new Error(`generated ${names.length} SDK functions for ${routes.length} operations`);
const api = [
  `// GENERATED by scripts/generate.mjs. Do not edit.`,
  `import type { Client } from './client/index.js';`,
  `import * as sdk from './sdk.gen.js';`,
  ``,
  `type Opts<F extends (...args: never[]) => unknown> = Omit<NonNullable<Parameters<F>[0]>, 'client' | 'throwOnError'>;`,
  `type Out<F extends (...args: never[]) => Promise<{ data: unknown }>> = Promise<Awaited<ReturnType<F>>['data']>;`,
  ``,
  `/** Every operation of the gateway as a method that returns the typed payload and throws on failure. */`,
  `export const bindApi = (client: Client) => ({`,
  ...names.map((n) => `  ${n}: async (options: Opts<typeof sdk.${n}<true>>${/options\?: /.test(sdkText.split(`export const ${n} = `)[1].split('\n')[0]) ? ' = {}' : ''}): Out<typeof sdk.${n}<true>> => (await sdk.${n}<true>({ ...options, client, throwOnError: true } as never)).data,`),
  `});`,
  ``,
  `export type Api = ReturnType<typeof bindApi>;`,
  ``,
].join('\n');
writeFileSync(join(out, 'api.gen.ts'), api);

const files = (dir) => readdirSync(dir, { recursive: true, withFileTypes: false }).filter((f) => statSync(join(dir, f)).isFile()).sort();
if (check) {
  const a = existsSync(TARGET) ? files(TARGET) : [];
  const b = files(out);
  const stale = [...new Set([...a, ...b])].filter((f) => !a.includes(f) || !b.includes(f) || readFileSync(join(TARGET, f), 'utf8') !== readFileSync(join(out, f), 'utf8'));
  rmSync(work, { recursive: true, force: true });
  if (stale.length) {
    console.error(`packages/api-client/src/generated is out of date with apps/api-gateway/openapi.json (${stale.join(', ')}). Run: npm run generate -w @oruschools/api-client, and commit the result.`);
    process.exit(1);
  }
  console.log('api-client: generated code is current');
} else {
  rmSync(TARGET, { recursive: true, force: true });
  mkdirSync(TARGET, { recursive: true });
  cpSync(out, TARGET, { recursive: true });
  rmSync(work, { recursive: true, force: true });
  console.log(`api-client: wrote ${relative(ROOT, TARGET)} (${routes.length} operations)`);
}
