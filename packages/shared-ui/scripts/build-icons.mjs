#!/usr/bin/env node
// Generates src/icons.generated.ts from the design system's own icon table (documentation/design-system/components/bundle.js,
// "Lucide-style 24px outline set"), so web icons are exactly the set the design owner drew. Never edit the output.
//   node scripts/build-icons.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BUNDLE = resolve(ROOT, '../../documentation/design-system/components/bundle.js');
const OUT = resolve(ROOT, 'src/icons.generated.ts');

const text = readFileSync(BUNDLE, 'utf8');
const start = text.indexOf('var USERS_BASE');
const end = text.indexOf('};', text.indexOf('var ICONS = {')) + 2;
if (start < 0 || end < 2) throw new Error('could not find the icon table in bundle.js');
const ICONS = new Function(`${text.slice(start, end)}; return ICONS;`)();

const names = Object.keys(ICONS);
const shape = (s) => (typeof s === 'string' ? { d: s } : s.c ? { c: s.c } : { r: s.r });
const body =
  `// GENERATED by scripts/build-icons.mjs from documentation/design-system/components/bundle.js. Do not edit.\n` +
  `export type IconShape = { d: string } | { c: [number, number, number] } | { r: [number, number, number, number, number] };\n` +
  `export const ICON_NAMES = ${JSON.stringify(names)} as const;\n` +
  `export type IconName = (typeof ICON_NAMES)[number];\n` +
  `export const ICON_SHAPES: Record<IconName, readonly IconShape[]> = ${JSON.stringify(Object.fromEntries(names.map((n) => [n, ICONS[n].map(shape)])), null, 2)};\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== body) {
    console.error('shared-ui: src/icons.generated.ts is out of date with the design system icon set. Run: npm run icons -w @oruschools/shared-ui');
    process.exit(1);
  }
  console.log(`shared-ui: ${names.length} icons, generated file is current`);
} else {
  writeFileSync(OUT, body);
  console.log(`shared-ui: wrote ${names.length} icons`);
}
