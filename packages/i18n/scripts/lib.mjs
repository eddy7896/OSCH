// Pure transforms for the i18n generator (no I/O). Source of truth: packages/i18n/locales.json + messages/*.json.
// ADR-0006: English is primary; every other language falls back to English per key until translated.

import { TYPE, parse } from "@formatjs/icu-messageformat-parser";

const HEADER = (what) =>
  `GENERATED by packages/i18n/scripts/build.mjs from packages/i18n/locales.json and messages/*.json (${what}).\nDo not edit by hand: run \`npm run i18n:build\`.`;

export const WEIGHT_NAMES = { 400: "Regular", 600: "SemiBold", 700: "Bold" };

/**
 * Parse an ICU message with the real parser (the same one next-intl uses), so quoting rules ('{x}' is literal text) and
 * structure (a plural/select MUST have an `other` branch) are judged exactly as at runtime.
 */
export function parseMessage(message) {
  return parse(message, { requiresOtherClause: true });
}

function collect(nodes, vars, state) {
  for (const n of nodes) {
    switch (n.type) {
      case TYPE.argument:
        if (vars.get(n.value) !== "int") vars.set(n.value, "String"); // a bare {count} inside a plural branch never downgrades the int
        break;
      case TYPE.number:
        vars.set(n.value, "int");
        break;
      case TYPE.date:
      case TYPE.time:
        vars.set(n.value, "String");
        break;
      case TYPE.plural:
        vars.set(n.value, "int");
        for (const opt of Object.values(n.options)) collect(opt.value, vars, state);
        break;
      case TYPE.select:
        if (vars.get(n.value) !== "int") vars.set(n.value, "String");
        for (const opt of Object.values(n.options)) collect(opt.value, vars, state);
        break;
      case TYPE.pound:
        state.pound = true;
        break;
      case TYPE.tag:
        collect(n.children, vars, state);
        break;
      default:
        break;
    }
  }
}

/** Placeholders in an ICU message: name -> Dart/ARB type. Plural variables are ints. Throws on invalid ICU. */
export function icuVars(message) {
  const vars = new Map();
  collect(parseMessage(message), vars, { pound: false });
  return vars;
}

/** True if the message uses ICU's `#` inside a plural: Flutter's gen-l10n does not substitute it (found by test), use {count}. */
export function usesPound(message) {
  const state = { pound: false };
  collect(parseMessage(message), new Map(), state);
  return state.pound;
}

/** Validation shared by the build, the unit tests and the evals. Returns a list of human-readable problems. */
export function validate(registry, catalogs, descriptions = {}) {
  const problems = [];
  const codes = registry.locales.map((l) => l.code);
  if (new Set(codes).size !== codes.length) problems.push("duplicate locale codes");
  const primary = registry.locales.filter((l) => l.tier === "primary");
  if (primary.length !== 1 || primary[0].code !== registry.default) problems.push(`exactly one primary locale, and it must be the default (${registry.default})`);
  for (const l of registry.locales) {
    if (!registry.scripts[l.font]) problems.push(`${l.code}: font "${l.font}" has no entry in scripts`);
    if (!["ltr", "rtl"].includes(l.dir)) problems.push(`${l.code}: dir must be ltr or rtl`);
    if (!codes.includes(l.flutterFallback) && !l.flutterFallback) problems.push(`${l.code}: missing flutterFallback`);
    if (!l.sample) problems.push(`${l.code}: missing sample text (needed for the glyph-coverage check)`);
  }
  const en = catalogs[registry.default] ?? {};
  const keys = Object.keys(en);
  if (keys.length === 0) problems.push("English catalog is empty");
  for (const [code, cat] of Object.entries(catalogs)) {
    if (!codes.includes(code)) problems.push(`catalog ${code}.json has no entry in locales.json`);
    for (const k of Object.keys(cat)) if (!(k in en)) problems.push(`${code}: key "${k}" does not exist in en.json`);
    for (const [k, v] of Object.entries(cat)) {
      if (typeof v !== "string" || v.trim() === "") problems.push(`${code}.${k}: empty or non-string`);
      else {
        if (/[<>]/.test(v)) problems.push(`${code}.${k}: HTML is not allowed in messages`);
        let vars;
        try {
          vars = icuVars(v);
          if (usesPound(v)) problems.push(`${code}.${k}: do not use # in plurals (Flutter gen-l10n does not substitute it); write {count}`);
        } catch (err) {
          problems.push(`${code}.${k}: invalid ICU message (${String(err.message ?? err).split("\n")[0]})`);
        }
        if (vars && code !== registry.default && k in en) {
          let enVars;
          try { enVars = icuVars(en[k]); } catch { enVars = new Map(); }
          const x = [...enVars.keys()].sort().join(","), y = [...vars.keys()].sort().join(",");
          if (x !== y) problems.push(`${code}.${k}: placeholders {${y}} differ from English {${x}}`);
        }
      }
    }
  }
  for (const k of keys) if (descriptions[k] === undefined) problems.push(`key "${k}" has no translator description`);
  return problems;
}

export function toLocalesTs(registry) {
  const rows = registry.locales.map((l) => `  { code: ${JSON.stringify(l.code)}, bcp47: ${JSON.stringify(l.bcp47)}, name: ${JSON.stringify(l.name)}, native: ${JSON.stringify(l.native)}, script: ${JSON.stringify(l.script)}, font: ${JSON.stringify(l.font)}, dir: ${JSON.stringify(l.dir)}, tier: ${JSON.stringify(l.tier)} },`);
  return `// ${HEADER("TypeScript locale registry").replace(/\n/g, "\n// ")}
export interface LocaleInfo {
  readonly code: string;
  readonly bcp47: string;
  readonly name: string;
  readonly native: string;
  readonly script: string;
  readonly font: string;
  readonly dir: "ltr" | "rtl";
  /** primary = default language; ready = complete draft catalog + fonts + direction verified; supported = fonts and direction only, UI falls back to English per key. */
  readonly tier: "primary" | "ready" | "supported";
}

export const LOCALES = [
${rows.join("\n")}
] as const satisfies readonly LocaleInfo[];

export type LocaleCode = (typeof LOCALES)[number]["code"];
export const DEFAULT_LOCALE: LocaleCode = ${JSON.stringify(registry.default)};
`;
}

export function toMessagesTs(registry, catalogs) {
  const body = registry.locales.map((l) => `  ${JSON.stringify(l.code)}: ${JSON.stringify(catalogs[l.code] ?? {}, null, 2).replace(/\n/g, "\n  ")},`).join("\n");
  return `// ${HEADER("message catalogs").replace(/\n/g, "\n// ")}
// Only translated keys are present per locale; getMessages() overlays them on English (per-key fallback).
import type { LocaleCode } from "./locales.generated.js";

export const MESSAGES: Readonly<Record<LocaleCode, Readonly<Record<string, string>>>> = {
${body}
};
`;
}

export function toArb(code, catalogs, descriptions, defaultCode) {
  const cat = catalogs[code] ?? {};
  const out = { "@@locale": code };
  for (const [k, v] of Object.entries(cat)) {
    out[k] = v;
    if (code === defaultCode) {
      const meta = { description: descriptions[k] };
      const vars = icuVars(v);
      if (vars.size) meta.placeholders = Object.fromEntries([...vars].map(([n, type]) => [n, { type }]));
      out[`@${k}`] = meta;
    }
  }
  return JSON.stringify(out, null, 2) + "\n";
}

export function toDartLocales(registry) {
  const families = [...new Set(Object.values(registry.scripts).map((s) => s.flutterFamily))];
  const rows = registry.locales.map((l) => {
    const script = registry.scripts[l.font];
    return `    OruLocale(code: '${l.code}', name: ${JSON.stringify(l.name)}, native: ${JSON.stringify(l.native)}, direction: TextDirection.${l.dir}, tier: OruLocaleTier.${l.tier}, flutterFallback: '${l.flutterFallback}', fontFamily: '${script.flutterFamily}', minLineHeight: ${script.minLineHeight ?? 0}),`;
  });
  return `// ${HEADER("Dart locale registry").replace(/\n/g, "\n// ")}
// ignore_for_file: public_member_api_docs
import 'package:flutter/widgets.dart';

enum OruLocaleTier { primary, ready, supported }

/// One supported language. [direction] is authoritative: Flutter's own RTL list lacks Kashmiri, so never rely on it.
class OruLocale {
  const OruLocale({
    required this.code,
    required this.name,
    required this.native,
    required this.direction,
    required this.tier,
    required this.flutterFallback,
    required this.fontFamily,
    required this.minLineHeight,
  });

  final String code;
  final String name;
  final String native;
  final TextDirection direction;
  final OruLocaleTier tier;

  /// Language whose Material/Widgets/Cupertino strings stand in when Flutter has none (Kashmiri, Dogri, Sindhi).
  final String flutterFallback;

  /// Primary bundled font family for this language's script.
  final String fontFamily;

  /// Minimum unitless line height the script needs (0 = use the design value).
  final double minLineHeight;

  Locale get locale => Locale(code);
  bool get isRtl => direction == TextDirection.rtl;
}

abstract final class OruLocales {
  static const String defaultCode = '${registry.default}';

  static const List<OruLocale> all = [
${rows.join("\n")}
  ];

  static List<Locale> get supportedLocales => [for (final l in all) l.locale];

  /// The registry entry for [locale] (language code only); English when unknown.
  static OruLocale of(Locale locale) => all.firstWhere((l) => l.code == locale.languageCode, orElse: () => all.first);

  static bool isSupported(Locale locale) => all.any((l) => l.code == locale.languageCode);
  static TextDirection textDirectionOf(Locale locale) => of(locale).direction;
}

/// Every bundled family (declared in pubspec.yaml). Used as the glyph-fallback chain behind the primary family.
abstract final class OruFontFamilies {
  static const List<String> all = [${families.map((f) => `'${f}'`).join(", ")}];
}
`;
}

/** Per-language font priority and minimum line heights as web CSS (applied by the `lang` attribute on <html>). */
export function toI18nCss(registry, textStyles) {
  const L = [`/* ${HEADER("per-language typography")} */`, "/* Browsers fall back per glyph through the --font-sans stack; these rules only choose the PRIMARY font and give tall scripts room. */"];
  const byFont = new Map();
  for (const l of registry.locales) {
    if (l.font === "Latin") continue;
    byFont.set(l.font, [...(byFont.get(l.font) ?? []), l.code]);
  }
  const base = Object.values(registry.scripts).map((s) => `var(${s.webVar})`);
  L.push("", "/* Every bundled script, for display fonts that only cover Latin (Poppins): `--font-display: var(--font-poppins), var(--font-script-stack)`. */", `:root {\n  --font-script-stack: ${base.join(", ")}, system-ui, sans-serif;\n}`);
  for (const [font, codes] of byFont) {
    const script = registry.scripts[font];
    const sel = (suffix = "") => codes.map((c) => `html:lang(${c})${suffix}`).join(",\n");
    const stack = [`var(${script.webVar})`, ...base.filter((v) => v !== `var(${script.webVar})`), "system-ui", "sans-serif"].join(", ");
    L.push("", `/* ${font}: ${codes.join(", ")} */`, `${sel()} {`, `  font-family: ${stack};`, "}");
    const tracked = textStyles.filter((s) => s.letterSpacingEm);
    if (tracked.length)
      L.push("/* Latin tracking (design: display -0.01em) breaks joined and conjunct scripts: none for any non-Latin language. */",
        ...tracked.map((s) => `${codes.map((c) => `html:lang(${c}) .text-${s.name}`).join(",\n")} {\n  letter-spacing: 0;\n}`));
    if (script.minLineHeight) {
      const rules = [];
      for (const s of textStyles) {
        const px = Math.ceil(script.minLineHeight * s.fontSize);
        if (px > s.lineHeight) rules.push(`${codes.map((c) => `html:lang(${c}) .text-${s.name}`).join(",\n")} {\n  line-height: ${px}px;\n}`);
      }
      if (rules.length) L.push(`/* min line height ${script.minLineHeight}x font size (design: max(design px, ceil(min x size))) */`, ...rules);
    }
  }
  return L.join("\n") + "\n";
}

export function toFontsTs(registry) {
  const entries = Object.entries(registry.scripts);
  const imports = entries.map(([, s]) => s.google).join(", ");
  const consts = entries.map(([name, s]) => {
    const varName = s.flutterFamily.charAt(0).toLowerCase() + s.flutterFamily.slice(1);
    const subsets = JSON.stringify(s.webSubsets);
    const weight = name === "Latin" ? `weight: ${JSON.stringify(s.weights.map(String))}, ` : ""; // all other Noto script fonts are variable fonts
    const preload = name === "Latin" ? "" : ", preload: false"; // only fetched when that script is actually rendered
    return `const ${varName} = ${s.google}({ variable: ${JSON.stringify(s.webVar)}, subsets: ${subsets}, ${weight}display: "swap"${preload} });`;
  });
  const vars = entries.map(([, s]) => `${s.flutterFamily.charAt(0).toLowerCase() + s.flutterFamily.slice(1)}.variable`);
  return `// ${HEADER("next/font loaders").replace(/\n/g, "\n// ")}
// Self-hosted at build time by next/font (no request to Google at runtime). Non-Latin fonts are lazy: the browser only
// downloads a script's font when text in that script is rendered (unicode-range) and \`preload\` is off.
import { ${imports} } from "next/font/google";

${consts.join("\n")}

/** Put on <html className>: defines every --font-noto-* CSS variable used by the --font-sans stack. */
export const fontVariables = [${vars.join(", ")}].join(" ");
`;
}

export function toPubspecFontsBlock(registry) {
  const lines = ["  # BEGIN GENERATED FONTS (packages/i18n/scripts/build.mjs; edit packages/i18n/locales.json, then run npm run i18n:build)"];
  lines.push("  # Bundled, never fetched: apps are offline-first. Built by tools/assets/make-flutter-fonts.py (SIL OFL licences in assets/fonts).", "  fonts:");
  for (const s of Object.values(registry.scripts)) {
    lines.push(`    - family: ${s.flutterFamily}`, "      fonts:");
    for (const w of s.weights) lines.push(`        - asset: assets/fonts/${s.flutterFamily}-${WEIGHT_NAMES[w]}.ttf`, `          weight: ${w}`);
  }
  lines.push("  # END GENERATED FONTS");
  return lines.join("\n") + "\n";
}

export function patchPubspec(pubspec, block) {
  const re = /  # BEGIN GENERATED FONTS[\s\S]*?  # END GENERATED FONTS\n/;
  if (!re.test(pubspec)) throw new Error("pubspec.yaml is missing the BEGIN/END GENERATED FONTS markers");
  return pubspec.replace(re, block);
}
