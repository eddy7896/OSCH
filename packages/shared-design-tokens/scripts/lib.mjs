// Pure token transforms (no I/O) so they can be unit-tested. Input: parsed tokens.json.
// DESIGN DECISION DS-1: light theme only. Dark values in tokens.json are intentionally NOT emitted.

const THEME = "light";

/** Names never exposed to product code: raw palette steps and app-icon colours (design-system/README.md "Colour"). */
const isHidden = (name) => /^indigo-\d+$/.test(name) || name.startsWith("app-");

export function resolveColors(tokens) {
  const raw = new Map(tokens.color.tokens.map((t) => [t.name, t.value]));
  const resolve = (name, seen = []) => {
    if (seen.includes(name)) throw new Error(`token alias cycle: ${[...seen, name].join(" -> ")}`);
    if (!raw.has(name)) throw new Error(`unknown token reference {${name}}`);
    let v = raw.get(name);
    if (typeof v === "object") v = v[THEME];
    if (typeof v !== "string") throw new Error(`token ${name} has no ${THEME} value`);
    const ref = v.match(/^\{(.+)\}$/);
    return ref ? resolve(ref[1], [...seen, name]) : v.toLowerCase();
  };
  const all = Object.fromEntries([...raw.keys()].map((n) => [n, resolve(n)]));
  for (const [n, v] of Object.entries(all)) if (!/^#[0-9a-f]{6}$/.test(v)) throw new Error(`token ${n} resolved to non-hex "${v}"`);
  return { all, product: Object.fromEntries(Object.entries(all).filter(([n]) => !isHidden(n))) };
}

export function collect(tokens) {
  const { all, product } = resolveColors(tokens);
  const kv = (group) => Object.fromEntries(group.tokens.map((t) => [t.name, t.value]));
  const shadow = Object.fromEntries(tokens.shadow.tokens.map((t) => [t.name, typeof t.value === "object" ? t.value[THEME] : t.value]));
  const styles = tokens.type.groups.flatMap((g) => g.styles).map((s) => ({
    name: s.name,
    fontSize: parseFloat(s.fontSize),
    lineHeight: parseFloat(s.lineHeight),
    fontWeight: s.fontWeight,
    letterSpacingEm: s.letterSpacing ? parseFloat(s.letterSpacing) : 0,
    tabular: ["stat", "stat-sm"].includes(s.name),
  }));
  return {
    colorAll: all,
    color: product,
    space: kv(tokens.spacing),
    radius: kv(tokens.radius),
    size: kv(tokens.size),
    shadow,
    fontSans: tokens.type.families.sans,
    styles,
  };
}

const HEADER = (what) =>
  `GENERATED by packages/shared-design-tokens/scripts/build.mjs from documentation/design-system/tokens.json (${what}).\nDo not edit by hand: run \`npm run tokens:build\`. Light theme only (decision DS-1).`;

export function toTokensCss(t) {
  const lines = [`/* ${HEADER("CSS variables")} */`, ":root {", "  color-scheme: light;"];
  for (const [n, v] of Object.entries(t.color)) lines.push(`  --${n}: ${v};`);
  for (const group of [t.space, t.radius, t.size, t.shadow]) for (const [n, v] of Object.entries(group)) lines.push(`  --${n}: ${v};`);
  lines.push(`  --font-sans-stack: ${t.fontSans};`, "}", "");
  return lines.join("\n");
}

/** Tailwind v4 theme. Resets Tailwind's default palette/radius/shadow/text scales so ONLY design tokens exist as utilities. */
export function toThemeCss(t, fontVars = ["--font-noto-sans", "--font-noto-sans-devanagari"]) {
  const L = [`/* ${HEADER("Tailwind v4 theme")} */`, "/* `inline` is required: our :root variables share names with theme variables (--radius-sm, --shadow-card), so non-inline would self-reference. */", "@theme inline {", "  /* Remove Tailwind defaults: no raw palette, no ad-hoc radii/shadows/sizes (design rule: semantic tokens only). */",
    "  --color-*: initial;", "  --radius-*: initial;", "  --shadow-*: initial;", "  --text-*: initial;", "", "  --color-transparent: transparent;", "  --color-current: currentColor;"];
  for (const n of Object.keys(t.color)) L.push(`  --color-${n}: var(--${n});`);
  L.push("");
  for (const n of Object.keys(t.radius)) L.push(`  --radius-${n.replace(/^radius-/, "")}: var(--${n});`);
  for (const n of Object.keys(t.shadow)) L.push(`  --shadow-${n.replace(/^shadow-/, "")}: var(--${n});`);
  L.push("", "  /* Font: next/font sets one --font-noto-* variable per script on <html> (packages/i18n/locales.json); browsers fall back per glyph. */",
    `  --font-sans: ${[...fontVars.map((v) => `var(${v})`), t.fontSans].join(", ")};`, "");
  for (const s of t.styles) {
    L.push(`  --text-${s.name}: ${s.fontSize}px;`, `  --text-${s.name}--line-height: ${s.lineHeight}px;`, `  --text-${s.name}--font-weight: ${s.fontWeight};`);
    if (s.letterSpacingEm) L.push(`  --text-${s.name}--letter-spacing: ${s.letterSpacingEm}em;`);
  }
  L.push("}", "");
  const tab = t.styles.filter((s) => s.tabular).map((s) => `.text-${s.name}`);
  L.push("/* Design system: stat numbers use tabular figures (Tailwind text-* theme values cannot carry font-variant-numeric). */",
    `${tab.join(",\n")} {`, "  font-variant-numeric: tabular-nums;", "}", "",
    "/* Spacing is NOT restricted to tokens: Tailwind's 4px step equals the design scale (p-1=space-1 ... p-12=space-12) but also allows other steps. */", "");
  return L.join("\n");
}

export function toTokensJs(t) {
  const data = { color: t.color, space: t.space, radius: t.radius, size: t.size, shadow: t.shadow, fontSans: t.fontSans, textStyles: t.styles };
  return `// ${HEADER("TypeScript module")}\nexport const tokens = ${JSON.stringify(data, null, 2)};\n`;
}

export function toTokensDts() {
  return `// ${HEADER("TypeScript types")}
export interface TextStyleToken { name: string; fontSize: number; lineHeight: number; fontWeight: number; letterSpacingEm: number; tabular: boolean }
export interface Tokens {
  color: Record<string, string>;
  space: Record<string, string>;
  radius: Record<string, string>;
  size: Record<string, string>;
  shadow: Record<string, string>;
  fontSans: string;
  textStyles: TextStyleToken[];
}
export declare const tokens: Tokens;
`;
}

// ---- Dart -------------------------------------------------------------------------------------
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const argb = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;
const rgba = (css) => {
  const m = css.match(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/);
  if (!m) throw new Error(`unsupported colour ${css}`);
  const a = Math.round(parseFloat(m[4]) * 255);
  return `0x${a.toString(16).padStart(2, "0").toUpperCase()}${[1, 2, 3].map((i) => parseInt(m[i]).toString(16).padStart(2, "0").toUpperCase()).join("")}`;
};
const px = (v) => `${parseFloat(v)}`;

export function toDart(t) {
  const L = [
    `// ${HEADER("Dart constants")}`.replace(/\n/g, "\n// "),
    "// ignore_for_file: public_member_api_docs",
    "import 'package:flutter/painting.dart';",
    "",
    "import 'locales.g.dart' show OruFontFamilies;",
    "",
    "/// Semantic colours (light theme). Raw palette steps and app-icon colours are intentionally absent.",
    "abstract final class OruColors {",
  ];
  for (const [n, v] of Object.entries(t.color)) L.push(`  static const Color ${camel(n)} = Color(${argb(v)});`);
  L.push("}", "", "abstract final class OruSpacing {");
  for (const [n, v] of Object.entries(t.space)) L.push(`  static const double ${camel(n)} = ${px(v)};`);
  L.push("}", "", "abstract final class OruRadius {");
  for (const [n, v] of Object.entries(t.radius)) L.push(`  static const double ${camel(n.replace(/^radius-/, ""))} = ${v === "999px" ? "999.0" : px(v)};`);
  L.push("}", "", "/// Control heights per density level and icon sizes.", "abstract final class OruSize {");
  for (const [n, v] of Object.entries(t.size)) L.push(`  static const double ${camel(n)} = ${px(v)};`);
  L.push("}", "", "abstract final class OruShadows {");
  for (const [n, v] of Object.entries(t.shadow)) {
    const m = v.match(/^0 (\d+)px (\d+)px (rgba\([^)]*\))$/);
    if (!m) throw new Error(`unsupported shadow ${v}`);
    L.push(`  static const List<BoxShadow> ${camel(n.replace(/^shadow-/, ""))} = [BoxShadow(color: Color(${rgba(m[3])}), offset: Offset(0, ${m[1]}), blurRadius: ${m[2]})];`);
  }
  L.push("}", "", "/// Bundled in packages/flutter-core/assets/fonts (apps are offline-first: fonts are never fetched at runtime).",
    "abstract final class OruFonts {", "  static const String package = 'flutter_core';", "  static const String sans = 'NotoSans';", "  /// Glyph-fallback chain: every bundled script family (generated from packages/i18n/locales.json).", "  static const List<String> fallback = OruFontFamilies.all;", "}", "", "abstract final class OruText {");
  for (const s of t.styles) {
    const feats = s.tabular ? ", fontFeatures: [FontFeature.tabularFigures()]" : "";
    const ls = s.letterSpacingEm ? `, letterSpacing: ${(s.letterSpacingEm * s.fontSize).toFixed(2)}` : "";
    L.push(`  static const TextStyle ${camel(s.name)} = TextStyle(fontFamily: OruFonts.sans, package: OruFonts.package, fontFamilyFallback: OruFonts.fallback, fontSize: ${s.fontSize}, height: ${(s.lineHeight / s.fontSize).toFixed(4)}, fontWeight: FontWeight.w${s.fontWeight}${ls}${feats});`);
  }
  L.push("}", "");
  return L.join("\n");
}
